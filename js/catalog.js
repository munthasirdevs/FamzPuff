// Helper to find product by id or slug
window.getVeloraProduct = function(idOrSlug) {
  if (!idOrSlug) return window.VELORA_CATALOG[0];
  const found = window.VELORA_CATALOG.find(p => p.id === idOrSlug || p.slug === idOrSlug);
  return found || window.VELORA_CATALOG[0];
};
